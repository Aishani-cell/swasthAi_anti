"""
Imaging and Radiology Schemas
"""
from typing import Optional, List
from pydantic import BaseModel, Field

class ImagingFinding(BaseModel):
    observation: str
    anatomical_location: Optional[str] = None
    confidence_score: Optional[float] = None
    verification_status: str = "NEEDS_REVIEW"
    severity: str = "NORMAL"  # NORMAL, MILD, MODERATE, SEVERE
    explanation: Optional[str] = None
    location_of_findings: Optional[str] = None
    abnormality_flag: Optional[str] = None

class RadiologyReport(BaseModel):
    modality: str = Field(..., pattern="^(CR|DX|CT|XR|MR|MRI|UNKNOWN)$")
    body_part: Optional[str] = None
    view_plane: Optional[str] = None  # e.g., "PA", "AP", "Axial", "Coronal", "Sagittal"
    image_quality: str = "ADEQUATE"  # GOOD, ADEQUATE, SUBOPTIMAL, UNREADABLE
    metadata_verified: bool = False
    findings: List[ImagingFinding] = []
    observed_findings: str = ""
    location_of_findings: str = ""
    relevant_abnormalities: List[str] = []
    uncertainty: str = "Moderate (assistive automated model observation)"
    limitations: str = "2D projection; assistive analysis only; not clinically validated diagnosis."
    extracted_text: Optional[str] = None
    summary_text: str = ""
    audit_flags: List[str] = []
    explanation: str = ""
    preview_url: Optional[str] = None
    human_review_required: bool = True
    clinical_disclaimer: str = "Image observations generated by assistive vision model; not clinically validated diagnostic interpretation. Independent radiologist verification required."
